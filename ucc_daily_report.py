def send_email(html_body, subject, config):
    msg = MIMEMultipart("mixed")
    msg["From"] = config["SENDER_EMAIL"]
    msg["To"] = ", ".join(config["RECEIVER_EMAILS"])
    if config["CC_EMAILS"]:
        msg["Cc"] = ", ".join(config["CC_EMAILS"])
    msg["Subject"] = subject

    msg.attach(MIMEText(html_body, "html"))

    if config["ATTACH_EXCEL"]:
        file_path = config["EXCEL_FILE_PATH"]
        if os.path.exists(file_path):
            with open(file_path, "rb") as f:
                part = MIMEBase("application", "octet-stream")
                part.set_payload(f.read())
            encoders.encode_base64(part)
            filename = os.path.basename(file_path)
            part.add_header("Content-Disposition", f"attachment; filename={filename}")
            msg.attach(part)
        else:
            print(f"Warning: attachment file not found, skipping: {file_path}")

    all_recipients = config["RECEIVER_EMAILS"] + config["CC_EMAILS"]

    try:
        with smtplib.SMTP(config["SMTP_SERVER"], config["SMTP_PORT"]) as server:
            server.starttls()
            server.login(config["SENDER_EMAIL"], config["SENDER_PASSWORD"])
            server.sendmail(config["SENDER_EMAIL"], all_recipients, msg.as_string())
        print(f"[{datetime.now()}] Email sent successfully!")
    except smtplib.SMTPAuthenticationError:
        print("ERROR: Authentication failed. Check email/password (use an App Password for Gmail).")
    except Exception as e:
        print(f"ERROR: Failed to send email -> {e}")


