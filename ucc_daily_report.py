def read_raw_data(config):
    """Read the raw UCC data from Excel (all rows kept, including duplicate complaint numbers)."""
    path = config["EXCEL_FILE_PATH"]
    if not os.path.exists(path):
        raise FileNotFoundError(f"Excel file not found: {path}")

    df = pd.read_excel(path, sheet_name=config["SHEET_NAME"])
    df.columns = df.columns.str.strip()  # remove accidental leading/trailing spaces in headers
    cols = config["COLUMNS"]

    required = [cols["CLIENT"], cols["CONNECTION"], cols["COMPLAINT_NO"], cols["DAYS"]]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(
            f"Missing expected column(s) in Excel: {missing}\n"
            f"Available columns: {list(df.columns)}\n"
            f"Update CONFIG['COLUMNS'] to match your actual headers."
        )

    return df


def build_client_summary(df, config):
    """Table 1: Client-wise Count of UCC (with Total row)."""
    cols = config["COLUMNS"]
    summary = (
        df.groupby(cols["CLIENT"])[cols["COMPLAINT_NO"]]
        .count()
        .reset_index()
        .rename(columns={cols["COMPLAINT_NO"]: "Count of UCC"})
        .sort_values("Count of UCC", ascending=False)
    )
    total_row = pd.DataFrame({cols["CLIENT"]: ["Total"], "Count of UCC": [summary["Count of UCC"].sum()]})
    summary = pd.concat([summary, total_row], ignore_index=True)
    summary = summary.rename(columns={cols["CLIENT"]: "Clients"})
    return summary


def build_connection_summary(df, config):
    """Table 2: Connection-wise Day-wise Pending summary (uses the existing 'Days' column)."""
    cols = config["COLUMNS"]

    def bucket(d):
        try:
            d = int(d)
        except (ValueError, TypeError):
            return "Day 1"
        if d <= 1:
            return "Day 1"
        elif d == 2:
            return "Day 2"
        else:
            return "3 Days & Above"

    df = df.copy()
    df["_Bucket"] = df[cols["DAYS"]].apply(bucket)

    pivot = pd.pivot_table(
        df,
        index=cols["CONNECTION"],
        columns="_Bucket",
        values=cols["COMPLAINT_NO"],
        aggfunc="count",
        fill_value=0,
    )

    for col in ["Day 1", "Day 2", "3 Days & Above"]:
        if col not in pivot.columns:
            pivot[col] = 0
    pivot = pivot[["Day 1", "Day 2", "3 Days & Above"]]

    pivot["Count of Complaint no"] = pivot.sum(axis=1)
    pivot = pivot.reset_index().rename(columns={cols["CONNECTION"]: "Connections"})

    grand_total = pd.DataFrame({
        "Connections": ["Grand Total"],
        "Day 1": [pivot["Day 1"].sum()],
        "Day 2": [pivot["Day 2"].sum()],
        "3 Days & Above": [pivot["3 Days & Above"].sum()],
        "Count of Complaint no": [pivot["Count of Complaint no"].sum()],
    })
    pivot = pd.concat([pivot, grand_total], ignore_index=True)
    return pivot


