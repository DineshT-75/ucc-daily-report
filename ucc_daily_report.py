def render_client_table(df, config):
    """Render Table 1 (Client-wise Count of UCC) as HTML."""
    header_bg = config["HEADER_BG_COLOR"]
    header_color = config["HEADER_TEXT_COLOR"]
    total_bg = config["TOTAL_ROW_BG_COLOR"]
    border = config["BORDER_COLOR"]
    font_family = config["TABLE_FONT"]
    font_size = config["TABLE_FONT_SIZE"]

    html = f"""
    <table style="border-collapse: collapse; font-family: {font_family}; font-size: {font_size}; border: 1px solid {border};">
        <tr>
            <th style="background-color:{header_bg}; color:{header_color}; padding:5px 8px; border:1px solid {border}; text-align:center;">Clients</th>
            <th style="background-color:{header_bg}; color:{header_color}; padding:5px 8px; border:1px solid {border}; text-align:center;">Count of UCC</th>
        </tr>
    """
    for _, row in df.iterrows():
        is_total = row["Clients"] == "Total"
        bg = total_bg if is_total else "#FFFFFF"
        weight = "bold" if is_total else "normal"
        html += f"""
        <tr style="background-color:{bg}; font-weight:{weight};">
            <td style="padding:4px 8px; border:1px solid {border};">{row['Clients']}</td>
            <td style="padding:4px 8px; border:1px solid {border}; text-align:center;">{row['Count of UCC']}</td>
        </tr>
        """
    html += "</table>"
    return html


